// ---------- تحلیل وزن ----------
data class Insight(
    val bmi: Double, val low: Double, val high: Double, val diff: Double,
    val goal: Goal, val weeksMin: Int, val weeksMax: Int,
    val warn: String?, val kcal: String
)

fun analyze(heightCm: Double, weight: Double, target: Double): Insight {
    val m = heightCm / 100.0
    val goal = if (target >= weight) Goal.MUSCLE else Goal.FAT
    val diff = abs(target - weight)
    // نرخ ایمن تغییر وزن در هفته (کیلوگرم): کاهش ۰٫۵ تا ۱، افزایش ۰٫۲۵ تا ۰٫۵
    val (fast, slow) = if (goal == Goal.FAT) 1.0 to 0.5 else 0.5 to 0.25
    val tBmi = target / (m * m)
    val warn = when {
        tBmi < 18.5 -> "وزن هدف تو پایین‌تر از محدوده سالم (BMI زیر ۱۸٫۵) است. لطفاً قبل از شروع با پزشک یا متخصص تغذیه مشورت کن."
        tBmi >= 30 -> "وزن هدف تو بالاتر از محدوده سالم است. بهتر است برنامه را با پزشک یا مربی هماهنگ کنی."
        else -> null
    }
    val kcal = if (goal == Goal.FAT)
        "برای کاهش وزن، حدود ۳۰۰ تا ۵۰۰ کیلوکالری کمتر از نیاز روزانه‌ات بخور و پروتئین کافی مصرف کن."
    else
        "برای افزایش وزن و عضله، حدود ۲۵۰ تا ۵۰۰ کیلوکالری بیشتر از نیاز روزانه‌ات بخور و پروتئین کافی مصرف کن."
    return Insight(
        bmi = weight / (m * m), low = 18.5 * m * m, high = 24.9 * m * m, diff = diff,
        goal = goal, weeksMin = ceil(diff / fast).toInt(), weeksMax = ceil(diff / slow).toInt(),
        warn = warn, kcal = kcal
    )
}
